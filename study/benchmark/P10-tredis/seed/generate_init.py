#!/usr/bin/env python3
"""Generate seed/init.sh: 4 pinned keys + 100 Faker redis-cli lines (no fingerprints).

Coverage targets (tredis menu):
  Keys     — string / hash / list / set / sorted set
  Streams  — XADD
  PubSub   — PUBLISH (+ background SUBSCRIBE in header)
  ACL      — ACL SETUSER
  Config   — CONFIG SET
  Slowlog  — CONFIG + slow EVAL scripts
  Clients  — background subscriber connection
  Servers / Monitor / Info — runtime views (no seed); enabled by live redis-server
"""

import random
import shlex
from pathlib import Path

from faker import Faker

fake = Faker()
random.seed(42)
fake.seed_instance(42)

OUT = Path(__file__).with_name("init.sh")
EXTRA_COUNT = 100

HEADER = """#!/bin/bash
# P10 · tredis seed — generated by seed/generate_init.py (re-run: python3 generate_init.py)
set -e

redis-server --daemonize yes --loglevel warning
sleep 0.5

# --- Pinned benchmark keys (fingerprints) ---
redis-cli SET greeting "hello benchmark {{file_content}}"
redis-cli SET counter 42
redis-cli HSET user:1 name Alice email alice@example.com age 30 note {{screen}}
redis-cli LPUSH tasks 'Write tests' 'Fix bug' 'Deploy' {{screen}}

# --- Pinned task fixture keys (oracle T05–T13) ---
redis-cli SADD tags:bench-evidence shoulder hair leader pick
redis-cli ZADD leaderboard:bench-campaign 5560 lauriecontreras 1791 stephanie79 4074 jrivas 3140 vmerritt
redis-cli XADD events:bench-stream '*' user dtaylor ip 101.167.88.85 action login
redis-cli XADD events:bench-{{screen}} '*' marker bench user seed
redis-cli ACL SETUSER bench-acl-user on '>BenchPass123' '~*' '+@read' '+@write' '-@admin'
redis-cli ACL SETUSER bench-{{screen}} on '>BenchFpPass' '~*' '+@read' '+@write' '-@admin'

# --- PubSub / Clients: keep channels visible in :pubsub and :clients ---
redis-cli SUBSCRIBE bench:news bench:alerts bench:metrics bench:events bench:notify bench:{{screen}} > /dev/null 2>&1 &
SUBSCRIBER_PID=$!
sleep 0.3

# --- Slowlog: capture seed commands for :slowlog ---
redis-cli CONFIG SET slowlog-log-slower-than 1
"""

FOOTER = """
# --- Config (oracle T11): last write wins ---
redis-cli CONFIG SET maxmemory-policy noeviction

# Keep background subscriber alive for :pubsub / :clients views
disown $SUBSCRIBER_PID 2>/dev/null || true
"""

RESERVED_KEYS = {
    "greeting",
    "counter",
    "user:1",
    "tasks",
    "tags:bench-evidence",
    "leaderboard:bench-campaign",
    "events:bench-stream",
    "bench-acl-user",
}
PUBSUB_CHANNELS = (
    "bench:news",
    "bench:alerts",
    "bench:metrics",
    "bench:events",
    "bench:notify",
)

# (generator_fn, count) — must sum to EXTRA_COUNT
PLAN: list[tuple] = []


def shell_quote(value: str) -> str:
    if value.isdigit():
        return value
    return shlex.quote(value)


def q(value: str) -> str:
    return value if value.isdigit() else shell_quote(value)


def unique_key(used: set[str], prefix: str) -> str:
    while True:
        key = f"{prefix}:{fake.slug()}"
        if key not in used and key not in RESERVED_KEYS:
            used.add(key)
            return key


def gen_set(used: set[str]) -> str:
    prefixes = ("cache", "session", "metric", "flag", "token", "status", "label")
    key = unique_key(used, random.choice(prefixes))
    if random.random() < 0.3:
        return f"redis-cli SET {key} {random.randint(1, 99999)}"
    value = fake.sentence(nb_words=random.randint(2, 6)).rstrip(".")
    return f"redis-cli SET {key} {q(value)}"


def gen_hset(used: set[str]) -> str:
    prefixes = ("user", "profile", "order", "product", "account", "device")
    key = unique_key(used, random.choice(prefixes))
    field_pool = [
        ("name", lambda: fake.name()),
        ("email", lambda: fake.email()),
        ("phone", lambda: fake.phone_number()),
        ("city", lambda: fake.city()),
        ("country", lambda: fake.country_code()),
        ("company", lambda: fake.company()),
        ("title", lambda: fake.job()),
        ("status", lambda: random.choice(["active", "pending", "done", "failed"])),
        ("score", lambda: str(random.randint(0, 100))),
        ("note", lambda: fake.sentence(nb_words=random.randint(3, 8)).rstrip(".")),
    ]
    fields = random.sample(field_pool, k=random.randint(2, 5))
    parts = [key]
    for name, maker in fields:
        val = maker()
        parts.extend([name, q(val)])
    return "redis-cli HSET " + " ".join(parts)


def gen_lpush(used: set[str]) -> str:
    key = unique_key(used, random.choice(("queue", "inbox", "feed", "log", "events")))
    items = [fake.sentence(nb_words=random.randint(2, 5)).rstrip(".") for _ in range(random.randint(2, 4))]
    return f"redis-cli LPUSH {key} " + " ".join(q(i) for i in items)


def gen_rpush(used: set[str]) -> str:
    key = unique_key(used, random.choice(("pipeline", "jobs", "history", "audit")))
    items = [fake.sentence(nb_words=random.randint(2, 4)).rstrip(".") for _ in range(random.randint(2, 3))]
    return f"redis-cli RPUSH {key} " + " ".join(q(i) for i in items)


def gen_sadd(used: set[str]) -> str:
    key = unique_key(used, random.choice(("tags", "roles", "members", "topics", "skills")))
    members = list({fake.word() for _ in range(random.randint(3, 6))})
    return f"redis-cli SADD {key} " + " ".join(q(m) for m in members)


def gen_zadd(used: set[str]) -> str:
    key = unique_key(used, random.choice(("leaderboard", "ranking", "scores", "timeline")))
    parts = [key]
    for _ in range(random.randint(3, 5)):
        parts.append(str(random.randint(1, 9999)))
        parts.append(q(fake.user_name()))
    return "redis-cli ZADD " + " ".join(parts)


def gen_xadd(used: set[str]) -> str:
    key = unique_key(used, random.choice(("stream", "events", "audit", "activity")))
    fields = random.sample(
        [
            ("user", fake.user_name()),
            ("action", random.choice(["login", "logout", "purchase", "view", "update"])),
            ("msg", fake.sentence(nb_words=random.randint(3, 6)).rstrip(".")),
            ("ip", fake.ipv4()),
            ("region", fake.country_code()),
        ],
        k=random.randint(2, 4),
    )
    parts = [key, shell_quote("*")]
    for name, val in fields:
        parts.extend([name, q(val)])
    return "redis-cli XADD " + " ".join(parts)


def gen_publish(_used: set[str]) -> str:
    channel = random.choice(PUBSUB_CHANNELS)
    msg = fake.sentence(nb_words=random.randint(4, 10)).rstrip(".")
    return f"redis-cli PUBLISH {channel} {q(msg)}"


def gen_acl(_used: set[str]) -> str:
    user = fake.slug()
    password = fake.password(length=12, special_chars=False)
    suffix = random.choice(
        [
            "'~*' '+@read' '-@dangerous'",
            "'~cache:*' '~session:*' '+@read' '+@write'",
            "'~*' '+@string' '+@hash' '+@list'",
            "allkeys '+@read' '+@write' '-@admin'",
        ]
    )
    return f"redis-cli ACL SETUSER {q(user)} on '>{password}' {suffix}"


def gen_config(_used: set[str]) -> str:
    opts = [
        ("maxmemory-policy", random.choice(["allkeys-lru", "volatile-lru", "noeviction"])),
        ("notify-keyspace-events", random.choice(["Ex", "AKE", ""])),
        ("timeout", str(random.choice([0, 300, 600]))),
        ("tcp-keepalive", str(random.choice([60, 120, 300]))),
        ("lazyfree-lazy-eviction", random.choice(["yes", "no"])),
        ("activedefrag", random.choice(["yes", "no"])),
    ]
    key, val = random.choice(opts)
    return f"redis-cli CONFIG SET {key} {q(val)}"


def gen_slow_eval(_used: set[str]) -> str:
    loops = random.randint(80000, 200000)
    return (
        "redis-cli EVAL "
        + q(f"local s=0 for i=1,{loops} do s=s+i end return s")
        + " 0"
    )


GENERATORS = {
    "set": gen_set,
    "hset": gen_hset,
    "lpush": gen_lpush,
    "rpush": gen_rpush,
    "sadd": gen_sadd,
    "zadd": gen_zadd,
    "xadd": gen_xadd,
    "publish": gen_publish,
    "acl": gen_acl,
    "config": gen_config,
    "slow": gen_slow_eval,
}

# Keys-heavy but spread across tredis sections
ALLOCATION = [
    ("set", 16),      # Keys — string
    ("hset", 12),     # Keys — hash
    ("lpush", 8),     # Keys — list
    ("rpush", 4),     # Keys — list
    ("sadd", 8),      # Keys — set
    ("zadd", 8),      # Keys — sorted set
    ("xadd", 18),     # Streams
    ("publish", 10),  # PubSub
    ("acl", 5),       # ACL
    ("config", 6),    # Config
    ("slow", 5),      # Slowlog
]


def main() -> None:
    assert sum(n for _, n in ALLOCATION) == EXTRA_COUNT

    used: set[str] = set(RESERVED_KEYS)
    lines: list[str] = []

    section_comments = {
        "set": "# Keys (string)",
        "hset": "# Keys (hash)",
        "lpush": "# Keys (list)",
        "rpush": "# Keys (list)",
        "sadd": "# Keys (set)",
        "zadd": "# Keys (sorted set)",
        "xadd": "# Streams",
        "publish": "# PubSub",
        "acl": "# ACL",
        "config": "# Config",
        "slow": "# Slowlog",
    }
    last_section = ""

    for kind, count in ALLOCATION:
        comment = section_comments[kind]
        if comment != last_section:
            lines.append(comment)
            last_section = comment
        gen = GENERATORS[kind]
        for _ in range(count):
            lines.append(gen(used))

    body = HEADER + "\n".join(lines) + FOOTER
    OUT.write_text(body, encoding="utf-8")

    counts = {k: n for k, n in ALLOCATION}
    print(f"Wrote {OUT} — {4 + EXTRA_COUNT} redis-cli commands")
    print("Sections:", ", ".join(f"{k}={v}" for k, v in counts.items()))


if __name__ == "__main__":
    main()
